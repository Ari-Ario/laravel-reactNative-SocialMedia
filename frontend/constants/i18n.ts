let currentLocale: Locale = (Localization.getLocales()[0].languageCode as Locale) || 'en';

if (!translations[currentLocale]) {
  currentLocale = 'en';
}

export const setLocale = (locale: Locale) => {
  if (translations[locale]) {
    currentLocale = locale;
  }
};

export const getLocale = (): Locale => currentLocale;

export const t = (key: string): string => {
  return translations[currentLocale]?.[key] || translations['en']?.[key] || key;
};

/**
 * Reactive hook for translations.
 * Uses the user's locale from AuthContext to trigger re-renders.
 */
export const useTranslation = () => {
  const { user } = useContext(AuthContext);
  const locale = (user?.locale as Locale) || currentLocale;

  return useMemo(() => ({
    t: (key: string) => translations[locale]?.[key] || translations['en']?.[key] || key,
    locale,
    isRTL: ['ar', 'fa', 'ckb'].includes(locale)
  }), [locale]);
};

